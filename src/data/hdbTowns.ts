/**
 * Resolve input query (town name, 6-digit postal code, or 2-digit sector) to a TownInfo object
 */
export function resolveTownFromQuery(query: string): TownInfo | null {
  const clean = query.trim().toUpperCase();
  if (!clean) return null;

  // 1. Exact or partial match on town ID or Name
  const foundByName = HDB_TOWNS.find(t => 
    t.id === clean || 
    t.name.toUpperCase() === clean ||
    t.name.toUpperCase().includes(clean)
  );
  if (foundByName) return foundByName;

  // 2. 6-digit postal code or 2-digit sector
  const digits = clean.replace(/\D/g, '');
  if (digits.length >= 2) {
    const sector = digits.slice(0, 2);
    const townId = POSTAL_SECTOR_TO_TOWN[sector];
    if (townId) {
      return HDB_TOWNS.find(t => t.id === townId) || null;
    }
  }

  return null;
}
